#!/usr/bin/env python3
"""Create a feature module (Python 3 standard library only) and register it everywhere it must be known.

    python3 -I new_feature.py --project . --name user-profile [--dry-run]

Creates :feature:<name> (tezca.android.feature convention plugin, Navigation 3 entries file, Hilt
module, strings.xml for every locale the project already has) and registers it in
settings.gradle.kts, app/build.gradle.kts and the app's AppNavDisplay.

Registrations are inserted right below the `// tezca-android:<anchor>` marker comments generated by
start-android. A missing marker is reported in "manual" (the agent then edits that file by hand);
nothing is overwritten. Prints a JSON report.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEMPLATES = HERE.parent / "assets" / "templates"
MARKER = "tezca-android"


def names(raw: str) -> dict[str, str]:
    parts = [w.lower() for w in re.split(r"[-_ ]+", raw.strip()) if w]
    if not parts or not re.fullmatch(r"[a-z][a-z0-9]*", parts[0]) or not all(re.fullmatch(r"[a-z0-9]+", p) for p in parts):
        raise SystemExit(f"Invalid feature name '{raw}': use letters/digits separated by dashes, e.g. user-profile")
    pascal = "".join(p.capitalize() for p in parts)
    return {
        "__FEATURE__": "-".join(parts),                      # module dir / Gradle name: user-profile
        "__FPKG__": "".join(parts),                          # package segment: userprofile
        "__Feature__": pascal,                               # class prefix: UserProfile
        "__feature__": pascal[:1].lower() + pascal[1:],      # fun prefix: userProfile
        "__feature_snake__": "_".join(parts),                # resource keys: user_profile
        "__Feature_Title__": " ".join(p.capitalize() for p in parts),
    }


def load_config(project: Path) -> dict:
    cfg_file = project / ".tezca-android.json"
    if cfg_file.exists():
        return json.loads(cfg_file.read_text(encoding="utf-8"))
    props = (project / "gradle.properties").read_text(encoding="utf-8") if (project / "gradle.properties").exists() else ""
    match = re.search(r"^tezca\.basePackage=(.+)$", props, re.M)
    if not match:
        raise SystemExit("No .tezca-android.json and no tezca.basePackage in gradle.properties: run start-android first.")
    return {"basePackage": match.group(1).strip(), "appId": match.group(1).strip(), "features": []}


def substitute(text: str, values: dict[str, str]) -> str:
    for key in sorted(values, key=len, reverse=True):
        text = text.replace(key, values[key])
    return text


def insert_after_marker(path: Path, anchor: str, lines: list[str], dry_run: bool, report: dict) -> None:
    """Insert `lines` after the line holding `// tezca-android:<anchor>`, keeping its indentation."""
    rel = str(path)
    if not path.exists():
        report["manual"].append(f"{rel}: file missing (expected marker {MARKER}:{anchor})")
        return
    text = path.read_text(encoding="utf-8")
    existing = {line.strip() for line in text.splitlines()}
    todo = [line for line in lines if line.strip() not in existing]
    if not todo:
        report["already_registered"].append(f"{rel} [{anchor}]")
        return
    out, done = [], False
    for line in text.splitlines(keepends=True):
        out.append(line)
        if not done and f"{MARKER}:{anchor}" in line:
            indent = re.match(r"\s*", line).group(0)
            out.extend(f"{indent}{new}\n" for new in todo)
            done = True
    if not done:
        report["manual"].append(f"{rel}: marker // {MARKER}:{anchor} not found; add {todo} by hand")
        return
    if not dry_run:
        path.write_text("".join(out), encoding="utf-8")
    report["edited"].append(f"{rel} [{anchor}] += {todo}")


def add_import(path: Path, import_line: str, dry_run: bool, report: dict) -> None:
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    if import_line in text.splitlines():
        return
    lines = text.splitlines(keepends=True)
    imports = [i for i, line in enumerate(lines) if line.startswith("import ")]
    if imports:
        pos = next((i for i in imports if lines[i].strip() > import_line), imports[-1] + 1)
    else:
        pos = next(i + 1 for i, line in enumerate(lines) if line.startswith("package "))
    lines.insert(pos, import_line + "\n")
    if not dry_run:
        path.write_text("".join(lines), encoding="utf-8")
    report["edited"].append(f"{path} += {import_line}")


def accessor(gradle_name: str) -> str:
    """Typesafe project accessor segment: user-profile -> userProfile."""
    head, *rest = gradle_name.split("-")
    return head + "".join(p.capitalize() for p in rest)


def project_locales(project: Path) -> list[str]:
    """Locale qualifiers the project already translates (values-es, values-pt-rBR...), taken from :core:ui."""
    res = project / "core" / "ui" / "src" / "main" / "res"
    if not res.is_dir():
        return []
    return sorted(
        d.name.removeprefix("values-") for d in res.iterdir()
        if d.is_dir() and re.fullmatch(r"values-[a-z]{2,3}(-r[A-Z]{2})?", d.name) and (d / "strings.xml").exists()
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--project", type=Path, default=Path("."))
    parser.add_argument("--name", required=True, help="Feature name, e.g. onboarding or user-profile")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    project = args.project.expanduser().resolve()
    cfg = load_config(project)
    pkg = cfg["basePackage"]
    app_id = cfg.get("appId") or pkg
    values = names(args.name)
    values.update({"__PKG_PATH__": pkg.replace(".", "/"), "__PKG__": pkg})
    feature, fpkg, camel = values["__FEATURE__"], values["__FPKG__"], values["__feature__"]
    report: dict = {"feature": feature, "module": f":feature:{feature}", "package": f"{pkg}.feature.{fpkg}",
                    "created": [], "skipped_existing": [], "edited": [], "already_registered": [], "manual": [],
                    "dry_run": args.dry_run}

    # 1. Files from templates
    root = TEMPLATES
    for src in sorted(p for p in root.rglob("*") if p.is_file() and p.name != ".DS_Store"):
        rel = Path(substitute(str(src.relative_to(root)), values))
        target = project / rel
        if target.exists():
            report["skipped_existing"].append(str(rel))
            continue
        if not args.dry_run:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(substitute(src.read_text(encoding="utf-8"), values), encoding="utf-8")
        report["created"].append(str(rel))

    # 2. One strings.xml per locale the project already ships, so translations are never forgotten.
    default_strings = project / "feature" / feature / "src" / "main" / "res" / "values" / "strings.xml"
    template_strings = substitute((TEMPLATES / "feature" / "__FEATURE__" / "src" / "main" / "res" / "values" / "strings.xml")
                                  .read_text(encoding="utf-8"), values)
    for locale in project_locales(project):
        target = default_strings.parent.parent / f"values-{locale}" / "strings.xml"
        rel = target.relative_to(project)
        if target.exists():
            report["skipped_existing"].append(str(rel))
            continue
        if not args.dry_run:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(template_strings, encoding="utf-8")
        report["created"].append(str(rel))

    # 3. Registrations
    insert_after_marker(project / "settings.gradle.kts", "features", [f'include(":feature:{feature}")'], args.dry_run, report)
    insert_after_marker(project / "app" / "build.gradle.kts", "feature-dependencies",
                        [f"implementation(projects.feature.{accessor(feature)})"], args.dry_run, report)
    nav = project / "app" / "src" / "main" / "kotlin" / app_id.replace(".", "/") / "navigation" / "AppNavDisplay.kt"
    if not nav.exists():
        found = list((project / "app" / "src" / "main").rglob("AppNavDisplay.kt"))
        nav = found[0] if found else nav
    add_import(nav, f"import {pkg}.feature.{fpkg}.navigation.{camel}Entries", args.dry_run, report)
    insert_after_marker(nav, "feature-entries", [f"{camel}Entries(navigator = navigator)"], args.dry_run, report)

    # 4. Project state
    cfg_file = project / ".tezca-android.json"
    if cfg_file.exists() and not args.dry_run:
        features = cfg.setdefault("features", [])
        if feature not in features:
            features.append(feature)
            cfg_file.write_text(json.dumps(cfg, indent=2) + "\n", encoding="utf-8")
            report["edited"].append(f".tezca-android.json features += {feature}")

    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
